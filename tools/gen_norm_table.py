"""Generate src/norm_table.h: code points removed by -normProb normalization.

The normalization matches the OpenLID-v2 / CommonLID input cleaner, which
deletes every character matching [^\\p{Word}\\p{Zs}]|\\d (non-word characters
and digits) after lowercasing. The table is computed with the same `regex`
module, so it agrees with that cleaner for the module's Unicode version.

Usage: python3 tools/gen_norm_table.py > src/norm_table.h   (needs `pip install regex`)
"""
import sys

import regex

REMOVED = regex.compile(r"[^\p{Word}\p{Zs}]|\d")


def ranges():
    start = None
    for cp in range(0x110000):
        removed = not (0xD800 <= cp <= 0xDFFF) and REMOVED.match(chr(cp)) is not None
        if removed and start is None:
            start = cp
        elif not removed and start is not None:
            yield start, cp - 1
            start = None
    if start is not None:
        yield start, 0x10FFFF


def main():
    rs = list(ranges())
    out = sys.stdout
    out.write("// Generated by tools/gen_norm_table.py with regex %s; do not edit.\n" % regex.__version__)
    out.write("// Code point ranges removed by [^\\p{Word}\\p{Zs}]|\\d, sorted by start.\n")
    out.write("#pragma once\n\n#include <cstdint>\n\nnamespace fasttext {\nnamespace unicode {\n\n")
    out.write("struct CodeRange {\n  uint32_t first;\n  uint32_t last;\n};\n\n")
    out.write("constexpr CodeRange kNormRemoved[] = {\n")
    for i in range(0, len(rs), 4):
        out.write("    %s,\n" % ", ".join("{0x%04X, 0x%04X}" % r for r in rs[i:i + 4]))
    out.write("};\n\nconstexpr int kNormRemovedSize = %d;\n\n" % len(rs))
    out.write("} // namespace unicode\n} // namespace fasttext\n")


if __name__ == "__main__":
    main()
