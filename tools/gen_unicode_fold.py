"""Generate src/unicode_fold.h: simple lowercase mappings for the CommonLID-style
normalization (-normProb).

Only one-to-one mappings are kept, so lowercasing never changes the number of
code points. U+0130 (capital I with dot above) lowercases to two code points
in Python; its simple mapping (UnicodeData.txt) is U+0069, which is used here.

Usage: python3 tools/gen_unicode_fold.py > src/unicode_fold.h
"""
import sys
import unicodedata

SPECIAL = {0x0130: 0x0069}


def mappings():
    for cp in range(0x80, 0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        if cp in SPECIAL:
            yield cp, SPECIAL[cp]
            continue
        lower = chr(cp).lower()
        if len(lower) == 1 and ord(lower) != cp:
            yield cp, ord(lower)


def main():
    pairs = list(mappings())
    out = sys.stdout
    out.write("// Generated by tools/gen_unicode_fold.py from Unicode %s; do not edit.\n"
              % unicodedata.unidata_version)
    out.write("// Simple (one-to-one) lowercase mappings for code points >= U+0080,\n"
              "// sorted by source code point. ASCII is folded separately.\n")
    out.write("#pragma once\n\n#include <cstdint>\n\nnamespace fasttext {\n"
              "namespace unicode {\n\n")
    out.write("struct FoldPair {\n  uint32_t from;\n  uint32_t to;\n};\n\n")
    out.write("constexpr const char* kFoldTableVersion = \"%s\";\n\n"
              % unicodedata.unidata_version)
    out.write("constexpr FoldPair kLowercase[] = {\n")
    for i in range(0, len(pairs), 4):
        row = ", ".join("{0x%04X, 0x%04X}" % p for p in pairs[i:i + 4])
        out.write("    %s,\n" % row)
    out.write("};\n\n")
    out.write("constexpr int kLowercaseSize = %d;\n\n" % len(pairs))
    out.write("} // namespace unicode\n} // namespace fasttext\n")


if __name__ == "__main__":
    main()
